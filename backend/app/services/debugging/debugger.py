import logging
from typing import List, Optional
from sqlalchemy.orm import Session
from app.models.repository import Repository
from app.models.user import User
from app.schemas.debug import DebugAnalyzeRequest, DebugAnalyzeResponse, SuggestedFixItem
from app.schemas.chat import CitationItem
from app.agents.debugging_graph import DebuggingGraphWorkflow
from app.core.exceptions import EntityNotFoundException

logger = logging.getLogger(__name__)


class DebuggerService:
    def __init__(self, db: Session, repository_id: str):
        self.db = db
        self.repository_id = repository_id
        self.workflow = DebuggingGraphWorkflow(db)

    def analyze_error(self, req: DebugAnalyzeRequest, user_id: Optional[str] = None) -> DebugAnalyzeResponse:
        """
        AI Debugging Workflow powered by LangGraph:
        1. Multi-step stateful graph orchestration.
        2. AST symbol & dependency inspection.
        3. Grounded hybrid code retrieval (Qdrant + PostgreSQL).
        4. Root cause diagnosis with source code line citations.
        5. Clean unified git diff patch creation & validation.
        6. Comprehensive pytest test case generation.
        """
        repo = self.db.query(Repository).filter(Repository.id == self.repository_id).first()
        if not repo:
            raise EntityNotFoundException("Repository", self.repository_id)

        target_user_id = user_id or repo.user_id

        # Execute LangGraph agent
        state = self.workflow.run(
            repository_id=self.repository_id,
            user_id=target_user_id,
            error_message=req.error_message,
            stack_trace=req.stack_trace or "",
            relevant_file=req.relevant_file,
            expected_behavior=req.expected_behavior
        )

        citations: List[CitationItem] = []
        for rc in state["retrieved_chunks"][:4]:
            citations.append(CitationItem(
                file_path=rc["file_path"],
                start_line=rc["start_line"],
                end_line=rc["end_line"],
                symbol_name=rc.get("symbol_name")
            ))

        fixes: List[SuggestedFixItem] = []
        if state["proposed_diff"]:
            fixes.append(SuggestedFixItem(
                file_path=state["target_file"] or (state["affected_files"][0] if state["affected_files"] else "unknown"),
                description=state["fix_description"] or "Defensive bugfix generated by LangGraph agent",
                unified_diff=state["proposed_diff"],
                validation_steps=[
                    "Inspect unified diff against target file.",
                    "Execute generated pytest test suite in isolated runner.",
                    "Approve patch to apply modifications to workspace."
                ],
                confidence=state["confidence"]
            ))

        tests_to_run = [
            f"pytest tests/ -k {state['extracted_symbols'][0]}"
            if state["extracted_symbols"] else "pytest backend/tests/"
        ]
        if state["generated_tests"]:
            tests_to_run.append("Execute generated regression unit tests.")

        return DebugAnalyzeResponse(
            run_id=state["agent_run_id"],
            patch_id=state.get("patch_id"),
            error_summary=req.error_message,
            potential_root_cause=state["root_cause_analysis"],
            evidence_from_codebase=state["evidence_from_codebase"],
            affected_files=state["affected_files"] or ([state["target_file"]] if state["target_file"] else []),
            citations=citations,
            suggested_fixes=fixes,
            tests_to_validate=tests_to_run,
            generated_tests=state.get("generated_tests"),
            confidence_limitations="Grounded in AST-indexed codebase context via LangGraph agent."
        )
